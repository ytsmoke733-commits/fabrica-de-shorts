// Caixa padrão: 1 grau = 1 unidade (360 x 150, de lat 90 a -60).
export const CAIXA_GRAUS = { x: 0, y: 0, w: 360, h: 150 };

// Equirretangular: lon -180..180 -> x..x+w; lat 90..-60 -> y..y+h (corta a Antártida).
export const projetar = ([lon, lat], { x, y, w, h }) => [x + ((lon + 180) / 360) * w, y + ((90 - lat) / 150) * h];

function dentro(poly, lon, lat) {
  let in_ = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) in_ = !in_;
  }
  return in_;
}

// O ponto [lon, lat] está em terra? (par-ímpar em algum polígono)
export const ehTerra = ([lon, lat]) => CONTINENTES.some((poly) => dentro(poly, lon, lat));

// Ponto p (0..1) da curva quadrática entre as projeções de a e b; o controle fica no meio,
// deslocado para cima por curva * distância. A caixa é opcional (padrão: CAIXA_GRAUS).
export function pontoDoArco(a, b, p, curva = 0.25, caixa = CAIXA_GRAUS) {
  const [ax, ay] = projetar(a, caixa), [bx, by] = projetar(b, caixa);
  const cx = (ax + bx) / 2, cy = (ay + by) / 2 - curva * Math.hypot(bx - ax, by - ay);
  const u = 1 - p;
  return [u * u * ax + 2 * u * p * cx + p * p * bx, u * u * ay + 2 * u * p * cy + p * p * by];
}
