// acentos: [letra base, marca]; marcas ocupam 2 linhas acima (ou 2 abaixo, na cedilha)
export const ACENTO = { Á: ['A', 'agudo'], À: ['A', 'grave'], Â: ['A', 'circ'], Ã: ['A', 'til'], É: ['E', 'agudo'], Ê: ['E', 'circ'], Í: ['I', 'agudo'],
  Ó: ['O', 'agudo'], Ô: ['O', 'circ'], Õ: ['O', 'til'], Ú: ['U', 'agudo'], Ü: ['U', 'trema'], Ç: ['C', 'cedilha'] };
// rabo que desce abaixo da linha de base (y 7 e 8), como a cedilha: vírgula e ponto e vírgula
export const DESCE = { ',': [[1, 7], [0, 8]], ';': [[1, 7], [0, 8]] };
const MARCA = { agudo: [[3, -2], [2, -1]], grave: [[1, -2], [2, -1]], circ: [[2, -2], [1, -1], [3, -1]], til: [[1, -2], [2, -2], [4, -2], [0, -1], [2, -1], [3, -1]],
  trema: [[1, -1], [3, -1]], cedilha: [[2, 7], [1, 8], [2, 8]] };

const cache = new Map();
/** caracteres pedidos que a fonte não tem (saíram como "?"); cada um também dispara console.error na 1ª vez, o que faz o capture.mjs check falhar */
export const faltando = new Set();
/** pixels do texto: { px: [[x, y], ...], w } em unidades de pixel da fonte (y 0 = topo da letra maiúscula) */
export function rasterizar(txt) {
  const k = String(txt);
  if (cache.has(k)) return cache.get(k);
  const px = []; let x = 0;
  for (const ch0 of k.toLocaleUpperCase('pt-BR')) {
    if (ch0 === ' ') { x += 4; continue; }
    const ac = ACENTO[ch0], ch = ac ? ac[0] : ch0, g = G[ch] || G['?'];
    if (!G[ch] && !faltando.has(ch0)) {
      faltando.add(ch0);
      // o capture.mjs check falha com console.error: o aviso sai na 1ª vez que o caractere é pedido (o cache não repete)
      console.error(`fonte pixel: sem glifo para "${ch0}" (U+${ch0.codePointAt(0).toString(16).toUpperCase().padStart(4, '0')})`);
    }
    g.forEach((row, y) => [...row].forEach((c, i) => { if (c === '#') px.push([x + i, y]); }));
    if (DESCE[ch]) for (const [i, y] of DESCE[ch]) px.push([x + i, y]);
    if (ac) for (const [i, y] of MARCA[ac[1]]) px.push([x + i, y]);
    x += g[0].length + 1;
  }
  const r = { px, w: Math.max(0, x - 1) };
  cache.set(k, r);
  return r;
}
export const larguraTexto = (txt, s) => rasterizar(txt).w * s;

/** desenha texto pixel. (x, y) = ponto de alinhamento; y é o topo da maiúscula. contorno = 1 pixel da fonte em volta */
export function textoPixel(txt, x, y, { s = 6, cor = '#FFF1C1', contorno = '#1A0F0A', alinhar = 'center', sombra = true, alpha = 1 } = {}) {
  const { px, w } = rasterizar(txt);
  const x0 = Math.round(alinhar === 'center' ? x - (w * s) / 2 : alinhar === 'right' ? x - w * s : x), y0 = Math.round(y);
  ctx.save(); ctx.globalAlpha *= alpha;
  if (contorno) {
    ctx.fillStyle = contorno;
    for (const [i, j] of px) ctx.fillRect(x0 + (i - 1) * s, y0 + (j - 1) * s, s * 3, s * (sombra ? 4 : 3));
  }
  ctx.fillStyle = cor;
  for (const [i, j] of px) ctx.fillRect(x0 + i * s, y0 + j * s, s, s);
  ctx.restore();
  return w * s;
}

/** vários pedaços coloridos numa linha só: partes = [{ txt, cor }] (espaço entre pedaços incluído) */
export function linhaPixel(partes, x, y, opts = {}) {
  const s = opts.s ?? 6, gap = 4 * s;
  const ws = partes.map((p) => larguraTexto(p.txt, s));
  const total = ws.reduce((a, b) => a + b, 0) + gap * (partes.length - 1);
  let cx = Math.round(x - total / 2);
  partes.forEach((p, i) => { textoPixel(p.txt, cx, y, { ...opts, cor: p.cor, alinhar: 'left' }); cx += ws[i] + gap; });
  return total;
}

